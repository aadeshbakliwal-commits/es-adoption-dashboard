-- 4-stage funnel snapshot (eligible / penetrated / activated / adopted) per feature,
-- as of the latest snapshot date. One row per feature. NESTED funnel: every stage is
-- counted within paid AND feature-eligible instances, so eligible >= penetrated >=
-- activated >= adopted.
--
-- Stage definitions:
--   eligible   = paid customer instances eligible for the feature (per-feature ELIGIBLE flag)
--   penetrated = PENETRATED flag (feature enabled / first meaningful use, 6mo lookback)
--   activated  = ACTIVATED flag (meaningful use within last 28 days, or ZDP's definition
--                for the platform features: active >=2 of the last 4 weeks)
--   adopted    = ADOPTED flag (sustained usage; ZDP defines per-feature thresholds)
--
-- Feature sources:
--   itam, service_catalog, change_management, tasks
--         -> FUNCTIONAL.PRODUCT_ANALYTICS.ES_ADOPTION_INSTANCE_DAILY_SNAPSHOT (change_management
--            uses the APPROVALS flags as the documented proxy)
--   es_ai_agents -> FUNCTIONAL.PRODUCT_ANALYTICS.AI_AGENTS_INSTANCE_DAILY_SNAPSHOT (paid flags)
--   action_flows, action_flow_connectors, mcp_actions
--         -> FUNCTIONAL.PRODUCT_ANALYTICS.PLATFORM_ADOPTION_INSTANCE_DAILY_SNAPSHOT
--            (ZDP-curated INSTANCE_IS_ACTION_FLOW_* / _CONNECTOR_* / _MCP_* funnels).
--            NOTE: this is the whole Action Flows product -- ZDP has NO advanced-vs-basic
--            Action Flows attribute, so "advanced_action_flows" is not reported.
--
-- PARAMETERS (edit before running):
SET end_date = '2026-10-19';   -- latest snapshot date to include per source
--
-- Run: snow sql -f sql/funnel_snapshot.sql --connection zdp-global

WITH es_latest AS (
    SELECT MAX(SOURCE_SNAPSHOT_DATE) AS snap_date
    FROM FUNCTIONAL.PRODUCT_ANALYTICS.ES_ADOPTION_INSTANCE_DAILY_SNAPSHOT
    WHERE SOURCE_SNAPSHOT_DATE <= $end_date
),
es AS (
    SELECT INSTANCE_ACCOUNT_ID, INSTANCE_IS_PAID_CUSTOMER,
           INSTANCE_IS_ITAM_ELIGIBLE, INSTANCE_IS_ITAM_PENETRATED, INSTANCE_IS_ITAM_ACTIVATED, INSTANCE_IS_ITAM_ADOPTED,
           INSTANCE_IS_SERVICE_CATALOG_ELIGIBLE, INSTANCE_IS_SERVICE_CATALOG_PENETRATED, INSTANCE_IS_SERVICE_CATALOG_ACTIVATED, INSTANCE_IS_SERVICE_CATALOG_ADOPTED,
           INSTANCE_IS_APPROVALS_ELIGIBLE, INSTANCE_IS_APPROVALS_PENETRATED, INSTANCE_IS_APPROVALS_ACTIVATED, INSTANCE_IS_APPROVALS_ADOPTED,
           INSTANCE_IS_TASKS_ELIGIBLE, INSTANCE_IS_TASKS_PENETRATED, INSTANCE_IS_TASKS_ACTIVATED, INSTANCE_IS_TASKS_ADOPTED
    FROM FUNCTIONAL.PRODUCT_ANALYTICS.ES_ADOPTION_INSTANCE_DAILY_SNAPSHOT
    WHERE SOURCE_SNAPSHOT_DATE = (SELECT snap_date FROM es_latest)
),
ai_latest AS (
    SELECT MAX(SOURCE_SNAPSHOT_DATE) AS snap_date
    FROM FUNCTIONAL.PRODUCT_ANALYTICS.AI_AGENTS_INSTANCE_DAILY_SNAPSHOT
    WHERE SOURCE_SNAPSHOT_DATE <= $end_date
),
ai AS (
    SELECT INSTANCE_ACCOUNT_ID, INSTANCE_IS_PAID_CUSTOMER,
           INSTANCE_IS_AI_AGENTS_ELIGIBLE, INSTANCE_IS_AI_AGENTS_PAID_PENETRATED, INSTANCE_IS_AI_AGENTS_PAID_ACTIVATED, INSTANCE_IS_AI_AGENTS_PAID_ADOPTED
    FROM FUNCTIONAL.PRODUCT_ANALYTICS.AI_AGENTS_INSTANCE_DAILY_SNAPSHOT
    WHERE SOURCE_SNAPSHOT_DATE = (SELECT snap_date FROM ai_latest)
),
pl_latest AS (
    SELECT MAX(SOURCE_SNAPSHOT_DATE) AS snap_date
    FROM FUNCTIONAL.PRODUCT_ANALYTICS.PLATFORM_ADOPTION_INSTANCE_DAILY_SNAPSHOT
    WHERE SOURCE_SNAPSHOT_DATE <= $end_date
),
pl AS (
    SELECT INSTANCE_ACCOUNT_ID, INSTANCE_IS_PAID_CUSTOMER,
           INSTANCE_IS_ACTION_FLOW_ELIGIBLE, INSTANCE_IS_ACTION_FLOW_PENETRATED, INSTANCE_IS_ACTION_FLOW_ACTIVATED, INSTANCE_IS_ACTION_FLOW_ADOPTED,
           INSTANCE_IS_CONNECTOR_ELIGIBLE, INSTANCE_IS_CONNECTOR_PENETRATED, INSTANCE_IS_CONNECTOR_ACTIVATED, INSTANCE_IS_CONNECTOR_ADOPTED,
           INSTANCE_IS_MCP_ELIGIBLE, INSTANCE_IS_MCP_PENETRATED, INSTANCE_IS_MCP_ACTIVATED, INSTANCE_IS_MCP_ADOPTED
    FROM FUNCTIONAL.PRODUCT_ANALYTICS.PLATFORM_ADOPTION_INSTANCE_DAILY_SNAPSHOT
    WHERE SOURCE_SNAPSHOT_DATE = (SELECT snap_date FROM pl_latest)
)
SELECT
    'itam' AS feature,
    (SELECT snap_date FROM es_latest) AS snapshot_date,
    COUNT(DISTINCT CASE WHEN e.INSTANCE_IS_PAID_CUSTOMER = TRUE AND e.INSTANCE_IS_ITAM_ELIGIBLE = TRUE THEN e.INSTANCE_ACCOUNT_ID END) AS eligible,
    COUNT(DISTINCT CASE WHEN e.INSTANCE_IS_PAID_CUSTOMER = TRUE AND e.INSTANCE_IS_ITAM_ELIGIBLE = TRUE AND e.INSTANCE_IS_ITAM_PENETRATED = TRUE THEN e.INSTANCE_ACCOUNT_ID END) AS penetrated,
    COUNT(DISTINCT CASE WHEN e.INSTANCE_IS_PAID_CUSTOMER = TRUE AND e.INSTANCE_IS_ITAM_ELIGIBLE = TRUE AND e.INSTANCE_IS_ITAM_ACTIVATED = TRUE THEN e.INSTANCE_ACCOUNT_ID END) AS activated,
    COUNT(DISTINCT CASE WHEN e.INSTANCE_IS_PAID_CUSTOMER = TRUE AND e.INSTANCE_IS_ITAM_ELIGIBLE = TRUE AND e.INSTANCE_IS_ITAM_ADOPTED = TRUE THEN e.INSTANCE_ACCOUNT_ID END) AS adopted
FROM es e
UNION ALL
SELECT 'service_catalog', (SELECT snap_date FROM es_latest),
    COUNT(DISTINCT CASE WHEN e.INSTANCE_IS_PAID_CUSTOMER = TRUE AND e.INSTANCE_IS_SERVICE_CATALOG_ELIGIBLE = TRUE THEN e.INSTANCE_ACCOUNT_ID END),
    COUNT(DISTINCT CASE WHEN e.INSTANCE_IS_PAID_CUSTOMER = TRUE AND e.INSTANCE_IS_SERVICE_CATALOG_ELIGIBLE = TRUE AND e.INSTANCE_IS_SERVICE_CATALOG_PENETRATED = TRUE THEN e.INSTANCE_ACCOUNT_ID END),
    COUNT(DISTINCT CASE WHEN e.INSTANCE_IS_PAID_CUSTOMER = TRUE AND e.INSTANCE_IS_SERVICE_CATALOG_ELIGIBLE = TRUE AND e.INSTANCE_IS_SERVICE_CATALOG_ACTIVATED = TRUE THEN e.INSTANCE_ACCOUNT_ID END),
    COUNT(DISTINCT CASE WHEN e.INSTANCE_IS_PAID_CUSTOMER = TRUE AND e.INSTANCE_IS_SERVICE_CATALOG_ELIGIBLE = TRUE AND e.INSTANCE_IS_SERVICE_CATALOG_ADOPTED = TRUE THEN e.INSTANCE_ACCOUNT_ID END)
FROM es e
UNION ALL
SELECT 'change_management', (SELECT snap_date FROM es_latest),
    COUNT(DISTINCT CASE WHEN e.INSTANCE_IS_PAID_CUSTOMER = TRUE AND e.INSTANCE_IS_APPROVALS_ELIGIBLE = TRUE THEN e.INSTANCE_ACCOUNT_ID END),
    COUNT(DISTINCT CASE WHEN e.INSTANCE_IS_PAID_CUSTOMER = TRUE AND e.INSTANCE_IS_APPROVALS_ELIGIBLE = TRUE AND e.INSTANCE_IS_APPROVALS_PENETRATED = TRUE THEN e.INSTANCE_ACCOUNT_ID END),
    COUNT(DISTINCT CASE WHEN e.INSTANCE_IS_PAID_CUSTOMER = TRUE AND e.INSTANCE_IS_APPROVALS_ELIGIBLE = TRUE AND e.INSTANCE_IS_APPROVALS_ACTIVATED = TRUE THEN e.INSTANCE_ACCOUNT_ID END),
    COUNT(DISTINCT CASE WHEN e.INSTANCE_IS_PAID_CUSTOMER = TRUE AND e.INSTANCE_IS_APPROVALS_ELIGIBLE = TRUE AND e.INSTANCE_IS_APPROVALS_ADOPTED = TRUE THEN e.INSTANCE_ACCOUNT_ID END)
FROM es e
UNION ALL
SELECT 'tasks', (SELECT snap_date FROM es_latest),
    COUNT(DISTINCT CASE WHEN e.INSTANCE_IS_PAID_CUSTOMER = TRUE AND e.INSTANCE_IS_TASKS_ELIGIBLE = TRUE THEN e.INSTANCE_ACCOUNT_ID END),
    COUNT(DISTINCT CASE WHEN e.INSTANCE_IS_PAID_CUSTOMER = TRUE AND e.INSTANCE_IS_TASKS_ELIGIBLE = TRUE AND e.INSTANCE_IS_TASKS_PENETRATED = TRUE THEN e.INSTANCE_ACCOUNT_ID END),
    COUNT(DISTINCT CASE WHEN e.INSTANCE_IS_PAID_CUSTOMER = TRUE AND e.INSTANCE_IS_TASKS_ELIGIBLE = TRUE AND e.INSTANCE_IS_TASKS_ACTIVATED = TRUE THEN e.INSTANCE_ACCOUNT_ID END),
    COUNT(DISTINCT CASE WHEN e.INSTANCE_IS_PAID_CUSTOMER = TRUE AND e.INSTANCE_IS_TASKS_ELIGIBLE = TRUE AND e.INSTANCE_IS_TASKS_ADOPTED = TRUE THEN e.INSTANCE_ACCOUNT_ID END)
FROM es e
UNION ALL
SELECT 'es_ai_agents', (SELECT snap_date FROM ai_latest),
    COUNT(DISTINCT CASE WHEN a.INSTANCE_IS_PAID_CUSTOMER = TRUE AND a.INSTANCE_IS_AI_AGENTS_ELIGIBLE = TRUE THEN a.INSTANCE_ACCOUNT_ID END),
    COUNT(DISTINCT CASE WHEN a.INSTANCE_IS_PAID_CUSTOMER = TRUE AND a.INSTANCE_IS_AI_AGENTS_ELIGIBLE = TRUE AND a.INSTANCE_IS_AI_AGENTS_PAID_PENETRATED = TRUE THEN a.INSTANCE_ACCOUNT_ID END),
    COUNT(DISTINCT CASE WHEN a.INSTANCE_IS_PAID_CUSTOMER = TRUE AND a.INSTANCE_IS_AI_AGENTS_ELIGIBLE = TRUE AND a.INSTANCE_IS_AI_AGENTS_PAID_ACTIVATED = TRUE THEN a.INSTANCE_ACCOUNT_ID END),
    COUNT(DISTINCT CASE WHEN a.INSTANCE_IS_PAID_CUSTOMER = TRUE AND a.INSTANCE_IS_AI_AGENTS_ELIGIBLE = TRUE AND a.INSTANCE_IS_AI_AGENTS_PAID_ADOPTED = TRUE THEN a.INSTANCE_ACCOUNT_ID END)
FROM ai a
UNION ALL
SELECT 'action_flows', (SELECT snap_date FROM pl_latest),
    COUNT(DISTINCT CASE WHEN p.INSTANCE_IS_PAID_CUSTOMER = TRUE AND p.INSTANCE_IS_ACTION_FLOW_ELIGIBLE = TRUE THEN p.INSTANCE_ACCOUNT_ID END),
    COUNT(DISTINCT CASE WHEN p.INSTANCE_IS_PAID_CUSTOMER = TRUE AND p.INSTANCE_IS_ACTION_FLOW_ELIGIBLE = TRUE AND p.INSTANCE_IS_ACTION_FLOW_PENETRATED = TRUE THEN p.INSTANCE_ACCOUNT_ID END),
    COUNT(DISTINCT CASE WHEN p.INSTANCE_IS_PAID_CUSTOMER = TRUE AND p.INSTANCE_IS_ACTION_FLOW_ELIGIBLE = TRUE AND p.INSTANCE_IS_ACTION_FLOW_ACTIVATED = TRUE THEN p.INSTANCE_ACCOUNT_ID END),
    COUNT(DISTINCT CASE WHEN p.INSTANCE_IS_PAID_CUSTOMER = TRUE AND p.INSTANCE_IS_ACTION_FLOW_ELIGIBLE = TRUE AND p.INSTANCE_IS_ACTION_FLOW_ADOPTED = TRUE THEN p.INSTANCE_ACCOUNT_ID END)
FROM pl p
UNION ALL
SELECT 'action_flow_connectors', (SELECT snap_date FROM pl_latest),
    COUNT(DISTINCT CASE WHEN p.INSTANCE_IS_PAID_CUSTOMER = TRUE AND p.INSTANCE_IS_CONNECTOR_ELIGIBLE = TRUE THEN p.INSTANCE_ACCOUNT_ID END),
    COUNT(DISTINCT CASE WHEN p.INSTANCE_IS_PAID_CUSTOMER = TRUE AND p.INSTANCE_IS_CONNECTOR_ELIGIBLE = TRUE AND p.INSTANCE_IS_CONNECTOR_PENETRATED = TRUE THEN p.INSTANCE_ACCOUNT_ID END),
    COUNT(DISTINCT CASE WHEN p.INSTANCE_IS_PAID_CUSTOMER = TRUE AND p.INSTANCE_IS_CONNECTOR_ELIGIBLE = TRUE AND p.INSTANCE_IS_CONNECTOR_ACTIVATED = TRUE THEN p.INSTANCE_ACCOUNT_ID END),
    COUNT(DISTINCT CASE WHEN p.INSTANCE_IS_PAID_CUSTOMER = TRUE AND p.INSTANCE_IS_CONNECTOR_ELIGIBLE = TRUE AND p.INSTANCE_IS_CONNECTOR_ADOPTED = TRUE THEN p.INSTANCE_ACCOUNT_ID END)
FROM pl p
UNION ALL
SELECT 'mcp_actions', (SELECT snap_date FROM pl_latest),
    COUNT(DISTINCT CASE WHEN p.INSTANCE_IS_PAID_CUSTOMER = TRUE AND p.INSTANCE_IS_MCP_ELIGIBLE = TRUE THEN p.INSTANCE_ACCOUNT_ID END),
    COUNT(DISTINCT CASE WHEN p.INSTANCE_IS_PAID_CUSTOMER = TRUE AND p.INSTANCE_IS_MCP_ELIGIBLE = TRUE AND p.INSTANCE_IS_MCP_PENETRATED = TRUE THEN p.INSTANCE_ACCOUNT_ID END),
    COUNT(DISTINCT CASE WHEN p.INSTANCE_IS_PAID_CUSTOMER = TRUE AND p.INSTANCE_IS_MCP_ELIGIBLE = TRUE AND p.INSTANCE_IS_MCP_ACTIVATED = TRUE THEN p.INSTANCE_ACCOUNT_ID END),
    COUNT(DISTINCT CASE WHEN p.INSTANCE_IS_PAID_CUSTOMER = TRUE AND p.INSTANCE_IS_MCP_ELIGIBLE = TRUE AND p.INSTANCE_IS_MCP_ADOPTED = TRUE THEN p.INSTANCE_ACCOUNT_ID END)
FROM pl p
ORDER BY feature;
