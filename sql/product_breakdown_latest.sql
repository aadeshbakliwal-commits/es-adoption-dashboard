-- Product/segment breakdown of ES feature adoption at the LATEST snapshot date.
-- Segment = CRM_MARKET_SUPER_SEGMENT from PRESENTATION.PRODUCT_ANALYTICS.PAID_CUSTOMER_UNIVERSE_DAILY_SNAPSHOT
-- (Digital / Corporate / Enterprise), joined on INSTANCE_ACCOUNT_ID. Joining to PCU also
-- restricts every feature to the paid customer universe, matching the monthly queries.
--
-- PARAMETERS (edit before running):
SET end_date = '2026-10-19';   -- upper bound; the query picks the latest snapshot <= this date per source
--
-- Run: snow sql -f sql/product_breakdown_latest.sql --connection zdp-global

WITH pcu AS (
    SELECT
        INSTANCE_ACCOUNT_ID,
        CRM_MARKET_SUPER_SEGMENT
    FROM PRESENTATION.PRODUCT_ANALYTICS.PAID_CUSTOMER_UNIVERSE_DAILY_SNAPSHOT
    WHERE IS_LATEST_DATE = TRUE
),
es AS (
    SELECT
        e.INSTANCE_ACCOUNT_ID,
        e.INSTANCE_IS_ITAM_ELIGIBLE,
        e.INSTANCE_IS_ITAM_PENETRATED,
        e.INSTANCE_IS_ITAM_ACTIVATED,
        e.INSTANCE_IS_SERVICE_CATALOG_ELIGIBLE,
        e.INSTANCE_IS_SERVICE_CATALOG_PENETRATED,
        e.INSTANCE_IS_SERVICE_CATALOG_ACTIVATED,
        e.INSTANCE_IS_APPROVALS_ELIGIBLE,
        e.INSTANCE_IS_APPROVALS_PENETRATED,
        e.INSTANCE_IS_APPROVALS_ACTIVATED
    FROM FUNCTIONAL.PRODUCT_ANALYTICS.ES_ADOPTION_INSTANCE_DAILY_SNAPSHOT e
    WHERE e.SOURCE_SNAPSHOT_DATE = (
        SELECT MAX(SOURCE_SNAPSHOT_DATE)
        FROM FUNCTIONAL.PRODUCT_ANALYTICS.ES_ADOPTION_INSTANCE_DAILY_SNAPSHOT
        WHERE SOURCE_SNAPSHOT_DATE <= $end_date
    )
),
ai AS (
    SELECT
        a.INSTANCE_ACCOUNT_ID,
        a.INSTANCE_IS_AI_AGENTS_ELIGIBLE,
        a.INSTANCE_IS_AI_AGENTS_PAID_PENETRATED,
        a.INSTANCE_IS_AI_AGENTS_PAID_ACTIVATED
    FROM FUNCTIONAL.PRODUCT_ANALYTICS.AI_AGENTS_INSTANCE_DAILY_SNAPSHOT a
    WHERE a.SOURCE_SNAPSHOT_DATE = (
        SELECT MAX(SOURCE_SNAPSHOT_DATE)
        FROM FUNCTIONAL.PRODUCT_ANALYTICS.AI_AGENTS_INSTANCE_DAILY_SNAPSHOT
        WHERE SOURCE_SNAPSHOT_DATE <= $end_date
    )
),
flows_ever AS (
    -- instances with any completed flow-step execution ever (up to end_date)
    SELECT
        f.INSTANCE_ACCOUNT_ID,
        SUM(f.COUNT_COMPLETED_ACTION_FLOW_STEP_EXECUTIONS) AS total_execs
    FROM PROPAGATED_FUNCTIONAL.PRODUCT_ANALYTICS.FACT_AGGREGATED_ACTION_FLOW_EXECUTIONS_DAILY_SNAPSHOT f
    WHERE f.SOURCE_SNAPSHOT_DATE <= $end_date
    GROUP BY 1
),
flows_latest_month AS (
    -- instances with >= 1 completed flow-step execution in the latest partial month (MTD)
    SELECT
        f.INSTANCE_ACCOUNT_ID,
        SUM(f.COUNT_COMPLETED_ACTION_FLOW_STEP_EXECUTIONS) AS month_execs
    FROM PROPAGATED_FUNCTIONAL.PRODUCT_ANALYTICS.FACT_AGGREGATED_ACTION_FLOW_EXECUTIONS_DAILY_SNAPSHOT f
    WHERE f.SOURCE_SNAPSHOT_DATE >= DATE_TRUNC('month', (SELECT MAX(SOURCE_SNAPSHOT_DATE)
        FROM PROPAGATED_FUNCTIONAL.PRODUCT_ANALYTICS.FACT_AGGREGATED_ACTION_FLOW_EXECUTIONS_DAILY_SNAPSHOT
        WHERE SOURCE_SNAPSHOT_DATE <= $end_date))
      AND f.SOURCE_SNAPSHOT_DATE <= $end_date
    GROUP BY 1
    HAVING SUM(f.COUNT_COMPLETED_ACTION_FLOW_STEP_EXECUTIONS) > 0
),
es_segmented AS (
    SELECT
        'itam'            AS feature,
        p.CRM_MARKET_SUPER_SEGMENT AS segment,
        COUNT(DISTINCT CASE WHEN e.INSTANCE_IS_ITAM_ELIGIBLE = TRUE THEN e.INSTANCE_ACCOUNT_ID END) AS accounts_total,
        COUNT(DISTINCT CASE WHEN e.INSTANCE_IS_ITAM_ELIGIBLE = TRUE AND e.INSTANCE_IS_ITAM_PENETRATED = TRUE THEN e.INSTANCE_ACCOUNT_ID END) AS activated_accounts,
        COUNT(DISTINCT CASE WHEN e.INSTANCE_IS_ITAM_ELIGIBLE = TRUE AND e.INSTANCE_IS_ITAM_ACTIVATED = TRUE THEN e.INSTANCE_ACCOUNT_ID END) AS accounts_using
    FROM es e
    INNER JOIN pcu p ON e.INSTANCE_ACCOUNT_ID = p.INSTANCE_ACCOUNT_ID
    GROUP BY 1, 2
    UNION ALL
    SELECT
        'service_catalog',
        p.CRM_MARKET_SUPER_SEGMENT,
        COUNT(DISTINCT CASE WHEN e.INSTANCE_IS_SERVICE_CATALOG_ELIGIBLE = TRUE THEN e.INSTANCE_ACCOUNT_ID END),
        COUNT(DISTINCT CASE WHEN e.INSTANCE_IS_SERVICE_CATALOG_ELIGIBLE = TRUE AND e.INSTANCE_IS_SERVICE_CATALOG_PENETRATED = TRUE THEN e.INSTANCE_ACCOUNT_ID END),
        COUNT(DISTINCT CASE WHEN e.INSTANCE_IS_SERVICE_CATALOG_ELIGIBLE = TRUE AND e.INSTANCE_IS_SERVICE_CATALOG_ACTIVATED = TRUE THEN e.INSTANCE_ACCOUNT_ID END)
    FROM es e
    INNER JOIN pcu p ON e.INSTANCE_ACCOUNT_ID = p.INSTANCE_ACCOUNT_ID
    GROUP BY 1, 2
    UNION ALL
    SELECT
        'change_management',
        p.CRM_MARKET_SUPER_SEGMENT,
        COUNT(DISTINCT CASE WHEN e.INSTANCE_IS_APPROVALS_ELIGIBLE = TRUE THEN e.INSTANCE_ACCOUNT_ID END),
        COUNT(DISTINCT CASE WHEN e.INSTANCE_IS_APPROVALS_ELIGIBLE = TRUE AND e.INSTANCE_IS_APPROVALS_PENETRATED = TRUE THEN e.INSTANCE_ACCOUNT_ID END),
        COUNT(DISTINCT CASE WHEN e.INSTANCE_IS_APPROVALS_ELIGIBLE = TRUE AND e.INSTANCE_IS_APPROVALS_ACTIVATED = TRUE THEN e.INSTANCE_ACCOUNT_ID END)
    FROM es e
    INNER JOIN pcu p ON e.INSTANCE_ACCOUNT_ID = p.INSTANCE_ACCOUNT_ID
    GROUP BY 1, 2
    UNION ALL
    SELECT
        'es_ai_agents',
        p.CRM_MARKET_SUPER_SEGMENT,
        COUNT(DISTINCT CASE WHEN a.INSTANCE_IS_AI_AGENTS_ELIGIBLE = TRUE THEN a.INSTANCE_ACCOUNT_ID END),
        COUNT(DISTINCT CASE WHEN a.INSTANCE_IS_AI_AGENTS_ELIGIBLE = TRUE AND a.INSTANCE_IS_AI_AGENTS_PAID_PENETRATED = TRUE THEN a.INSTANCE_ACCOUNT_ID END),
        COUNT(DISTINCT CASE WHEN a.INSTANCE_IS_AI_AGENTS_ELIGIBLE = TRUE AND a.INSTANCE_IS_AI_AGENTS_PAID_ACTIVATED = TRUE THEN a.INSTANCE_ACCOUNT_ID END)
    FROM ai a
    INNER JOIN pcu p ON a.INSTANCE_ACCOUNT_ID = p.INSTANCE_ACCOUNT_ID
    GROUP BY 1, 2
    UNION ALL
    SELECT
        'action_flows',
        p.CRM_MARKET_SUPER_SEGMENT,
        COUNT(DISTINCT p.INSTANCE_ACCOUNT_ID),
        COUNT(DISTINCT fe.INSTANCE_ACCOUNT_ID),              -- activated = any execution ever (paid instances)
        COUNT(DISTINCT flm.INSTANCE_ACCOUNT_ID)              -- using = >=1 execution in the latest month (MTD)
    FROM pcu p
    LEFT JOIN flows_ever fe ON fe.INSTANCE_ACCOUNT_ID = p.INSTANCE_ACCOUNT_ID AND fe.total_execs > 0
    LEFT JOIN flows_latest_month flm ON flm.INSTANCE_ACCOUNT_ID = p.INSTANCE_ACCOUNT_ID
    GROUP BY 1, 2
)
SELECT * FROM es_segmented ORDER BY feature, segment;
