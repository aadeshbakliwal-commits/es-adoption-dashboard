-- Source freshness: max snapshot date + row/date coverage per source table used by the
-- ES feature adoption dashboard. Run after any refresh to update "data as of".
--
-- Run: snow sql -f sql/source_freshness.sql --connection zdp-global

SELECT 'FUNCTIONAL.PRODUCT_ANALYTICS.ES_ADOPTION_INSTANCE_DAILY_SNAPSHOT' AS source_table,
       MIN(SOURCE_SNAPSHOT_DATE) AS min_snapshot_date,
       MAX(SOURCE_SNAPSHOT_DATE) AS max_snapshot_date,
       COUNT(DISTINCT SOURCE_SNAPSHOT_DATE) AS n_snapshot_dates
FROM FUNCTIONAL.PRODUCT_ANALYTICS.ES_ADOPTION_INSTANCE_DAILY_SNAPSHOT
UNION ALL
SELECT 'FUNCTIONAL.PRODUCT_ANALYTICS.AI_AGENTS_INSTANCE_DAILY_SNAPSHOT',
       MIN(SOURCE_SNAPSHOT_DATE), MAX(SOURCE_SNAPSHOT_DATE), COUNT(DISTINCT SOURCE_SNAPSHOT_DATE)
FROM FUNCTIONAL.PRODUCT_ANALYTICS.AI_AGENTS_INSTANCE_DAILY_SNAPSHOT
UNION ALL
SELECT 'PROPAGATED_FUNCTIONAL.PRODUCT_ANALYTICS.FACT_AGGREGATED_ACTION_FLOW_EXECUTIONS_DAILY_SNAPSHOT',
       MIN(SOURCE_SNAPSHOT_DATE), MAX(SOURCE_SNAPSHOT_DATE), COUNT(DISTINCT SOURCE_SNAPSHOT_DATE)
FROM PROPAGATED_FUNCTIONAL.PRODUCT_ANALYTICS.FACT_AGGREGATED_ACTION_FLOW_EXECUTIONS_DAILY_SNAPSHOT
UNION ALL
SELECT 'PRESENTATION.PRODUCT_ANALYTICS.ES_USAGE_INSTANCE_DAILY_SNAPSHOT',
       MIN(SOURCE_SNAPSHOT_DATE), MAX(SOURCE_SNAPSHOT_DATE), COUNT(DISTINCT SOURCE_SNAPSHOT_DATE)
FROM PRESENTATION.PRODUCT_ANALYTICS.ES_USAGE_INSTANCE_DAILY_SNAPSHOT
UNION ALL
SELECT 'PRESENTATION.PRODUCT_ANALYTICS.PAID_CUSTOMER_UNIVERSE_DAILY_SNAPSHOT',
       MIN(SOURCE_SNAPSHOT_DATE), MAX(SOURCE_SNAPSHOT_DATE), COUNT(DISTINCT SOURCE_SNAPSHOT_DATE)
FROM PRESENTATION.PRODUCT_ANALYTICS.PAID_CUSTOMER_UNIVERSE_DAILY_SNAPSHOT
ORDER BY source_table;
